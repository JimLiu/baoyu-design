#!/usr/bin/env node
/**
 * Regenerates the copied parts of skills/claude-dashboard from the Dashboard type sources.
 *
 *   node tools/artifact-skills/sync-dashboard.mjs [--build]
 *
 * Writes
 *   skills/claude-dashboard/scripts/editor/index.html   the built page, patched to boot standalone (see patchIndex)
 *   skills/claude-dashboard/scripts/editor/assets/      the built JS and CSS, as built
 *   skills/claude-dashboard/artifact-type/reference/    the type's references, verbatim
 *   tools/artifact-skills/dashboard/upstream.json      sha256 of every source copied, and of the original SKILL.md
 *
 * Sources: CLAUDE_SKILLS_DIR (default ../claude-skills), its src/dashboard-type/dist (the TypeScript reconstruction of
 * the runtime, built with `npm run build`) and originals/dashboard-type (SKILL.md and artifact-type/reference/).
 * --build runs `vite build` there into a temp folder first (needs its node_modules), instead of copying its dist/.
 *
 * Hand-written and never touched here: SKILL.md, scripts/artifact.mjs, scripts/editor/local-host.js.
 * When the original SKILL.md's hash differs from upstream.json, the script says so: port the change by hand.
 */
import { execFileSync } from 'node:child_process';
import { createHash } from 'node:crypto';
import fs from 'node:fs';
import os from 'node:os';
import path from 'node:path';
import { fileURLToPath } from 'node:url';

const here = path.dirname(fileURLToPath(import.meta.url));
const repo = path.resolve(here, '../..');
const claudeSkills = path.resolve(process.env.CLAUDE_SKILLS_DIR ?? path.join(repo, '../claude-skills'));
const typeSrc = path.join(claudeSkills, 'src/dashboard-type');
const original = path.join(claudeSkills, 'originals/dashboard-type');
const skill = path.join(repo, 'skills/claude-dashboard');
const editorOut = path.join(skill, 'scripts/editor');
const upstreamFile = path.join(here, 'dashboard/upstream.json');

function fail(message) {
  console.error(message);
  process.exit(1);
}

for (const p of [typeSrc, original]) if (!fs.existsSync(p)) fail(`Missing ${p}; set CLAUDE_SKILLS_DIR to the claude-skills checkout.`);

const sha = (file) => createHash('sha256').update(fs.readFileSync(file)).digest('hex');

// ---- 1. the built page ----
let dist = path.join(typeSrc, 'dist');
if (process.argv.includes('--build')) {
  dist = fs.mkdtempSync(path.join(os.tmpdir(), 'dashboard-dist-'));
  execFileSync(path.join(typeSrc, 'node_modules/.bin/vite'), ['build', '--outDir', dist, '--emptyOutDir'], { cwd: typeSrc, stdio: 'inherit' });
}
const distIndex = path.join(dist, 'index.html');
if (!fs.existsSync(distIndex)) fail(`No ${distIndex}: run \`npm run build\` in ${typeSrc}, or pass --build.`);

/**
 * The built index.html is the claude.ai page. Changes, each checked to apply exactly once:
 *  - the inline health monitor (artifact.json + appifact-health) is removed: it reports to a parent frame that isn't there;
 *  - the README comment and <meta name="README"> (written for Claude on claude.ai, naming its ArtifactData tool) are
 *    replaced by a short local note;
 *  - appifact-capabilities keeps only what the local host provides. The runtime reads its `db` key (live-store mode)
 *    and `downloads` key; mcp, room and comments are dropped because there are no connectors, room or comments here;
 *  - local-host.js (globalThis.claude over HTTP to artifact.mjs serve) loads before the module script;
 *  - asset URLs become relative (./assets/), so the page works under any path.
 */
function patchIndex(html) {
  const once = (label, re, replacement) => {
    const matches = html.match(new RegExp(re.source, re.flags.includes('g') ? re.flags : re.flags + 'g'));
    if (!matches || matches.length !== 1) fail(`patchIndex: expected one ${label}, found ${matches ? matches.length : 0}. The built page changed; update sync-dashboard.mjs.`);
    html = html.replace(re, replacement);
  };
  once('health monitor script', /<script>\(\(\) => \{\n {2}\/\/ artifact\.json[\s\S]*?\n\}\)\(\);<\/script>\n/, '');
  once('README comment', /<!-- README\n[\s\S]*?\n-->\n/, '');
  once('README meta', /<meta name="README" content="[^"]*">\n/, '');
  const capabilities = {
    downloads: {},
    db: { rules: [{ path: '', write: 'admin' }, { path: 'data/users/{self}', read: 'view', write: 'interact' }] },
    assets: {},
    user: { scopes: ['profile'] },
  };
  const attr = JSON.stringify(capabilities).replaceAll('&', '&amp;').replaceAll('"', '&quot;');
  once('capabilities meta', /<meta name="appifact-capabilities" content="[^"]*">/, `<meta name="appifact-capabilities" content="${attr}">`);
  const note =
    '<!--\n' +
    '  claude-dashboard: the claude.ai Dashboard type runtime, served locally by scripts/artifact.mjs serve.\n' +
    '  A dashboard\'s content is its store, <root>/db/<collection>/<doc_id>.json; local-host.js gives the runtime\n' +
    '  globalThis.claude (db, assets, user, downloads) over HTTP to that server. Regenerated by\n' +
    '  tools/artifact-skills/sync-dashboard.mjs; see SKILL.md.\n' +
    '-->\n';
  once('title', /<title>Dashboard<\/title>\n/, `<title>Dashboard</title>\n${note}`);
  once('module script', /\n( *)<script type="module" crossorigin src="\/assets\//, '\n$1<script src="./local-host.js"></script>\n$1<script type="module" crossorigin src="./assets/');
  once('stylesheet', /<link rel="stylesheet" crossorigin href="\/assets\//, '<link rel="stylesheet" crossorigin href="./assets/');
  if (/appifact-health|__frame_health|ArtifactData/.test(html)) fail('patchIndex: platform text survived the patch.');
  return html;
}

fs.mkdirSync(editorOut, { recursive: true });
fs.rmSync(path.join(editorOut, 'assets'), { recursive: true, force: true });
fs.cpSync(path.join(dist, 'assets'), path.join(editorOut, 'assets'), { recursive: true });
fs.writeFileSync(path.join(editorOut, 'index.html'), patchIndex(fs.readFileSync(distIndex, 'utf8')));
if (!fs.existsSync(path.join(editorOut, 'local-host.js'))) fail(`Missing ${path.join(editorOut, 'local-host.js')} (hand-written; restore it from git).`);

// ---- 2. the references, verbatim ----
const refFrom = path.join(original, 'artifact-type/reference');
const refTo = path.join(skill, 'artifact-type/reference');
fs.rmSync(refTo, { recursive: true, force: true });
fs.mkdirSync(refTo, { recursive: true });
for (const name of fs.readdirSync(refFrom).filter((n) => n.endsWith('.md')).sort()) fs.copyFileSync(path.join(refFrom, name), path.join(refTo, name));

// ---- 3. what was copied, and whether SKILL.md needs a manual port ----
const assets = fs.readdirSync(path.join(editorOut, 'assets')).sort();
const record = {
  originalSkill: { file: 'originals/dashboard-type/SKILL.md', sha256: sha(path.join(original, 'SKILL.md')) },
  references: Object.fromEntries(fs.readdirSync(refTo).sort().map((n) => [n, sha(path.join(refTo, n))])),
  dist: { index: sha(distIndex), assets: Object.fromEntries(assets.map((n) => [n, sha(path.join(editorOut, 'assets', n))])) },
};
let previous = null;
try {
  previous = JSON.parse(fs.readFileSync(upstreamFile, 'utf8'));
} catch {}
fs.mkdirSync(path.dirname(upstreamFile), { recursive: true });
fs.writeFileSync(upstreamFile, `${JSON.stringify(record, null, 2)}\n`);

const size = assets.reduce((n, a) => n + fs.statSync(path.join(editorOut, 'assets', a)).size, 0);
console.log(`editor: ${assets.join(', ')} (${(size / 1024 / 1024).toFixed(1)} MB) -> ${path.relative(repo, editorOut)}`);
console.log(`references: ${Object.keys(record.references).join(', ')} -> ${path.relative(repo, refTo)}`);
if (previous && previous.originalSkill?.sha256 !== record.originalSkill.sha256) {
  console.log('NOTE: the original SKILL.md changed since the last sync. Port the change into skills/claude-dashboard/SKILL.md by hand.');
}
